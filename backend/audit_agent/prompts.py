def normalize_prompt_profile(profile: dict | None, category: str | None = None) -> dict:
    category_id = str((profile or {}).get("category_id") or (profile or {}).get("category") or category or "soft").strip() or "soft"
    default = DEFAULT_PROMPT_PROFILES.get(category_id, DEFAULT_PROMPT_PROFILES["soft"])
    try:
        version = int((profile or {}).get("version") or default.get("version") or 1)
    except (TypeError, ValueError):
        version = int(default.get("version") or 1)
    preview = (profile or {}).get("preview") or {}
    return {
        "category_id": category_id,
        "audit_goal": str((profile or {}).get("audit_goal") or default.get("audit_goal") or "").strip(),
        "evidence_rules": str((profile or {}).get("evidence_rules") or default.get("evidence_rules") or "").strip(),
        "fusion_rules": str((profile or {}).get("fusion_rules") or default.get("fusion_rules") or "").strip(),
        "image_prompt": _prompt_value((profile or {}).get("image_prompt") or preview.get("image_prompt"), default["image_prompt"]),
        "frame_prompt": _prompt_value((profile or {}).get("frame_prompt") or preview.get("frame_prompt"), default["frame_prompt"]),
        "fusion_prompt_template": _prompt_value(
            (profile or {}).get("fusion_prompt_template") or preview.get("fusion_prompt_template"),
            default["fusion_prompt_template"],
        ),
        "version": version,
        "prompt_version": str(
            (profile or {}).get("prompt_version")
            or default.get("prompt_version")
            or f"{category_id}-profile-v{version}"
        ).strip(),
        "updated_at": str((profile or {}).get("updated_at") or ""),
    }


def build_prompt_set_from_profile(profile: dict | None, category: str | None = None) -> PromptSet:
    normalized = normalize_prompt_profile(profile, category)
    return PromptSet(
        category=normalized["category_id"],
        prompt_version=normalized["prompt_version"],
        image_prompt=normalized["image_prompt"],
        frame_prompt=normalized["frame_prompt"],
        fusion_prompt_template=normalized["fusion_prompt_template"],
    )


def render_prompt_profile_preview(profile: dict | None, category: str | None = None) -> dict:
    prompt_set = build_prompt_set_from_profile(profile, category)
    return {
        "image_prompt": prompt_set.image_prompt,
        "frame_prompt": prompt_set.frame_prompt,
        "fusion_prompt_template": prompt_set.fusion_prompt_template,
    }


def _prompt_value(value, default: str) -> str:
    if isinstance(value, str) and value.strip():
        return value
    return default


